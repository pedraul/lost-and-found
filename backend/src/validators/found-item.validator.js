const Joi = require('joi');

const registerFoundItemSchema = Joi.object({
  // Item Information (Required)
  item_name: Joi.string().max(255).required().messages({
    'string.max': 'Item name cannot exceed 255 characters',
    'any.required': 'Item name is required'
  }),
  item_category: Joi.string().max(50).required().messages({
    'string.max': 'Item category cannot exceed 50 characters',
    'any.required': 'Item category is required'
  }),
  item_description: Joi.string().allow('', null).max(5000).messages({
    'string.max': 'Item description cannot exceed 5000 characters'
  }),

  // Identifiers (Conditional by Category)
  serial_number: Joi.string().allow('', null).max(100).messages({
    'string.max': 'Serial number cannot exceed 100 characters'
  }),
  imei_number: Joi.string().pattern(/^[0-9]{15}$/).allow('', null).messages({
    'string.pattern.base': 'IMEI must be exactly 15 digits'
  }),
  vin_number: Joi.string().pattern(/^[A-HJ-NPR-Z0-9]{17}$/).allow('', null).messages({
    'string.pattern.base': 'VIN must be exactly 17 characters'
  }),
  passport_number: Joi.string().max(20).allow('', null).messages({
    'string.max': 'Passport number cannot exceed 20 characters'
  }),
  id_number: Joi.string().max(100).allow('', null).messages({
    'string.max': 'ID number cannot exceed 100 characters'
  }),
  license_plate: Joi.string().max(20).allow('', null).messages({
    'string.max': 'License plate cannot exceed 20 characters'
  }),
  frame_size: Joi.string().max(20).allow('', null).messages({
    'string.max': 'Frame size cannot exceed 20 characters'
  }),

  // Physical Attributes
  condition: Joi.string().allow('', null).valid('Excellent', 'Good', 'Fair', 'Poor', 'Damaged').messages({
    'any.only': 'Condition must be one of: Excellent, Good, Fair, Poor, Damaged'
  }),
  color: Joi.string().max(50).allow('', null).messages({
    'string.max': 'Color cannot exceed 50 characters'
  }),
  brand: Joi.string().max(100).allow('', null).messages({
    'string.max': 'Brand cannot exceed 100 characters'
  }),
  model: Joi.string().max(100).allow('', null).messages({
    'string.max': 'Model cannot exceed 100 characters'
  }),
  distinctive_marks: Joi.string().allow('', null).max(2000).messages({
    'string.max': 'Distinctive marks cannot exceed 2000 characters'
  }),
  additional_notes: Joi.string().allow('', null).max(5000).messages({
    'string.max': 'Additional notes cannot exceed 5000 characters'
  }),

  // Found Location
  found_location: Joi.string().max(500).required().messages({
    'string.max': 'Found location cannot exceed 500 characters',
    'any.required': 'Found location is required'
  }),
  found_latitude: Joi.number().min(-90).max(90).precision(8).allow(null).messages({
    'number.min': 'Latitude cannot be less than -90',
    'number.max': 'Latitude cannot exceed 90'
  }),
  found_longitude: Joi.number().min(-180).max(180).precision(8).allow(null).messages({
    'number.min': 'Longitude cannot be less than -180',
    'number.max': 'Longitude cannot exceed 180'
  }),
  found_address: Joi.string().allow('', null).max(500).messages({
    'string.max': 'Found address cannot exceed 500 characters'
  }),
  found_city: Joi.string().max(100).allow('', null).messages({
    'string.max': 'Found city cannot exceed 100 characters'
  }),
  found_country: Joi.string().max(100).allow('', null).messages({
    'string.max': 'Found country cannot exceed 100 characters'
  }),

  // Found Date & Time
  found_date: Joi.date().required().messages({
    'date.base': 'Found date must be a valid date',
    'any.required': 'Found date is required'
  }),
  found_time: Joi.string().allow('', null).regex(/^([01]\d|2[0-3]):([0-5]\d)$/).messages({
    'string.pattern.base': 'Found time must be in HH:mm format'
  }),
  found_datetime: Joi.date().allow(null).messages({
    'date.base': 'Found datetime must be a valid datetime'
  }),

  // Verification Code (auto-generated by backend)
  found_verification_code: Joi.string().length(19).required().messages({
    'string.length': 'Verification code must be exactly 19 characters',
    'any.required': 'Verification code is required'
  }),
  found_verification_hash: Joi.string().max(255).required().messages({
    'string.max': 'Verification code hash cannot exceed 255 characters',
    'any.required': 'Verification code hash is required'
  }),
  qr_code_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'QR code URL must be a valid URL'
  }),

  // Images (all required)
  overall_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Overall image URL must be a valid URL'
  }),
  overall_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Overall file name cannot exceed 255 characters'
  }),
  serial_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Serial image URL must be a valid URL'
  }),
  serial_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Serial file name cannot exceed 255 characters'
  }),
  front_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Front image URL must be a valid URL'
  }),
  front_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Front file name cannot exceed 255 characters'
  }),
  back_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Back image URL must be a valid URL'
  }),
  back_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Back file name cannot exceed 255 characters'
  }),
  side_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Side image URL must be a valid URL'
  }),
  side_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Side file name cannot exceed 255 characters'
  }),
  interior_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Interior image URL must be a valid URL'
  }),
  interior_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Interior file name cannot exceed 255 characters'
  }),
  damage_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Damage image URL must be a valid URL'
  }),
  damage_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Damage file name cannot exceed 255 characters'
  }),
  distinctive_image_url: Joi.string().uri().allow('', null).messages({
    'string.uri': 'Distinctive image URL must be a valid URL'
  }),
  distinctive_file_name: Joi.string().max(255).allow('', null).messages({
    'string.max': 'Distinctive file name cannot exceed 255 characters'
  }),

  // Status tracking
  status: Joi.string()
    .valid('pending', 'matched', 'claimed', 'returned', 'resolved', 'expired')
    .default('pending')
    .messages({
      'any.only': 'Invalid status value'
    }),

  // Security & Privacy
  is_public: Joi.boolean().default(true).messages({
    'any.only': 'is_public must be a boolean'
  }),
  show_reporter_contact: Joi.boolean().default(false).messages({
    'any.only': 'show_reporter_contact must be a boolean'
  })
});

module.exports = { registerFoundItemSchema };